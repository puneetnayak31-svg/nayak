def render_lines(lines, cols, rows_per_line=9):
    """Centre each line in a grid `cols` wide; returns a (len(lines)*rows_per_line, cols) 0/1 array."""
    out = np.zeros((len(lines) * rows_per_line, cols), np.float32)
    for li, ln in enumerate(lines):
        ln = ln.upper()
        w = len(ln) * 6 - 1
        x0 = max(0, (cols - w) // 2)
        y0 = li * rows_per_line + 1
        for ci, ch in enumerate(ln):
            g = G.get(ch, G[" "])
            for r in range(7):
                for c in range(5):
                    if g[r][c] == "1":
                        xx = x0 + ci * 6 + c
                        if 0 <= xx < cols:
                            out[y0 + r, xx] = 1
    return out
