/* ------------------------------ misc helpers ------------------------------ */

export function Loading({ title, steps }: { title: string; steps?: string[] }) {
  const [i, setI] = useState(0);
  useEffect(() => {
    if (!steps?.length) return;
    const t = setInterval(() => setI((x) => (x + 1) % steps.length), 1800);
    return () => clearInterval(t);
  }, [steps]);
  return (
    <div className="stack gap-16 center" style={{ alignItems: 'center', padding: '48px 16px' }} aria-busy="true">
      <SparkLoader size={80} />
      <div className="stack gap-6" style={{ alignItems: 'center' }}>
        <strong className="display" style={{ fontSize: 24 }}>
          {title}
        </strong>
        {steps && (
          <span key={i} className="muted fade-up">
            {steps[i]}
          </span>
        )}
      </div>
    </div>
  );
}

export function CopyButton({ text, label = 'Copy' }: { text: string; label?: string }) {
  const { toast } = useApp();
  return (
    <button
      type="button"
      className="btn btn-ghost btn-xs no-print"
      onClick={() => {
        navigator.clipboard?.writeText(text).then(
          () => toast('Copied'),
          () => toast('Could not copy', 'error'),
        );
      }}
    >
      {label}
    </button>
  );
}

/** Load Google Fonts for a user brand on demand. */
export function useGoogleFonts(families: Array<{ family: string; weights: number[] }> | undefined) {
  const key = families?.map((f) => `${f.family}:${f.weights.join(',')}`).join('|');
  useEffect(() => {
    if (!families?.length) return;
    const href = googleFontsHref(families);
    if (document.querySelector(`link[data-gf="${CSS.escape(href)}"]`)) return;
    const link = document.createElement('link');
    link.rel = 'stylesheet';
    link.href = href;
    link.dataset.gf = href;
    document.head.appendChild(link);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [key]);
}

