def sentences(text):
    """Split a description into its sentences (each keeps its danda)."""
    parts = [p.strip() for p in text.split("।") if p.strip()]
    return [p + "।" for p in parts]


def clips():
    """Every narration clip: key -> text. Each sentence is its own clip so text can follow the voice."""
    out = {f"intro{i}": t for i, t in enumerate(INTRO)}
    for slug, _, desc in GODDESSES:
        for j, s in enumerate(sentences(desc), 1):
            out[f"{slug}-{j}"] = s
    out.update({f"outro{i}": t for i, t in enumerate(OUTRO)})
    return out
