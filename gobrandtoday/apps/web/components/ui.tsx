export function ScoreBreakdown({ score, compact }: { score: GoBrandScore; compact?: boolean }) {
  return (
    <div className="stack gap-12">
      {score.components.map((c) => (
        <div key={c.key} className="stack gap-6">
          <div className="row between gap-12">
            <span style={{ fontWeight: 700, fontSize: 14.5 }}>{c.label}</span>
            <span className="mono small">{c.value === null ? '—' : c.value.toFixed(1)}</span>
          </div>
          <div className={`bar ${c.value === null ? 'pending' : ''}`}>
            <span style={{ width: `${(c.value ?? 0) * 10}%` }} />
          </div>
          {!compact && <span className="tiny muted">{c.note}</span>}
        </div>
      ))}
      <p className="tiny muted">
        Weights: {score.components.map((c) => `${c.label} ${c.weight}%`).join(' · ')}. The score is guidance — not a guarantee of trademark clearance, search rankings or success.
      </p>
    </div>
  );
}

export function Risks({ score }: { score: GoBrandScore }) {
  const risks = score.risks.filter((r) => r.level !== 'info');
  if (!risks.length) return null;
  return (
    <div className="stack gap-8">
      {risks.map((r) => (
        <div key={r.message} className={`notice ${r.level === 'high' ? 'error' : 'warn'}`}>
          {r.message}
        </div>
      ))}
    </div>
  );
}

/* ------------------------------ domain table ------------------------------ */

export function DomainTable({ results, onWatch }: { results: DomainResult[]; onWatch?: (d: DomainResult) => void }) {
  return (
    <div className="table-scroll">
      <table className="table">
        <thead>
          <tr>
            <th>Domain</th>
            <th>Status</th>
            <th className="hide-sm">Checked with</th>
            <th style={{ textAlign: 'right' }}>Get it</th>
          </tr>
        </thead>
        <tbody>
          {results.map((r) => (
            <tr key={r.domain}>
              <td className="mono" style={{ fontSize: 15 }}>
                {r.domain}
                {r.price && (
                  <div className="tiny muted">
                    {new Intl.NumberFormat('en-IN', { style: 'currency', currency: r.price.currency }).format(r.price.amount)}
                  </div>
                )}
              </td>
              <td>
                <DomainStatus r={r} />
                {r.note && r.status !== 'taken' && <div className="tiny muted" style={{ marginTop: 6, maxWidth: 300 }}>{r.note}</div>}
              </td>
              <td className="hide-sm tiny muted">{r.verified ? `✓ ${sourceLabel(r.source)}` : r.source === 'demo' ? 'Demo data' : 'Not verified'}</td>
              <td style={{ textAlign: 'right' }}>
                {r.buyLinks.length > 0 ? (
                  <BuyMenu r={r} />
                ) : r.status === 'taken' && onWatch ? (
                  <button className="btn btn-ghost btn-xs" onClick={() => onWatch(r)}>
                    Watch
                  </button>
                ) : (
                  <span className="tiny muted">—</span>
                )}
              </td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

function BuyMenu({ r }: { r: DomainResult }) {
  const [primary, ...rest] = r.buyLinks;
  if (!primary) return null;
  return (
    <div className="row gap-6" style={{ justifyContent: 'flex-end', flexWrap: 'wrap' }}>
      <a
        className="btn btn-primary btn-xs"
        href={primary.url}
        target="_blank"
        rel="noopener noreferrer sponsored"
        onClick={() => track('purchase_link_clicked', { domain: r.domain, registrar: primary.registrar })}
      >
        {r.status === 'unknown' ? 'Check on' : 'Buy on'} {primary.label}
      </a>
      {rest.map((l) => (
        <a
          key={l.registrar}
          className="btn btn-ghost btn-xs"
          href={l.url}
          target="_blank"
          rel="noopener noreferrer sponsored"
          onClick={() => track('purchase_link_clicked', { domain: r.domain, registrar: l.registrar })}
        >
          {l.label}
        </a>
      ))}
    </div>
  );
}

